#!/usr/bin/env python3
"""Generate the repository's measured-facts documents.

Two files are produced, both under `docs/_generated/`:

* `GATE_METRICS.md` - deterministic structural facts (test files, collected
  tests, module/script counts, documentation pages, the GNN pin, exemplar
  count). `--check` compares it byte-for-byte with a fresh generation, so a
  stale number fails the docs arm instead of drifting.
* `ARM_TIMINGS.md` - the last measured wall time per gate arm, read from
  `docs/_generated/arm-timings.jsonl`, which `./run.sh` appends to on this
  host. `--check` validates its shape, not its values: timings are
  host-specific measurements, never a claim about another machine.

No number in either file is hand-written. Run `./run.sh metrics` to refresh.

Usage:
    python software/scripts/generate_gate_metrics.py           # write both files
    python software/scripts/generate_gate_metrics.py --check   # verify they are current
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOFTWARE = ROOT / "software"
GENERATED = ROOT / "docs" / "_generated"
METRICS_PATH = GENERATED / "GATE_METRICS.md"
TIMINGS_PATH = GENERATED / "ARM_TIMINGS.md"
TIMINGS_LOG = GENERATED / "arm-timings.jsonl"
COVERAGE_JSON = SOFTWARE / "coverage.json"
PIN_PATH = ROOT / ".github" / "gnn-pin.json"
MODELS_DIR = ROOT / "course_development" / "gnn" / "01_gnn_syntax" / "models"

ARMS = ("lint", "types", "no-mocks", "test", "test-full", "docs", "contract", "gnn")
COLLECTED_RE = re.compile(r"(\d+) tests? collected")


def _rel(path: Path) -> str:
    return str(path.relative_to(ROOT))


def count_collected_tests() -> int:
    """Return the number of tests pytest collects, with project addopts neutralized."""
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "tests/", "--collect-only", "-q", "-o", "addopts="],
        cwd=SOFTWARE,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode not in (0, 5):
        raise RuntimeError(f"pytest --collect-only failed:\n{proc.stdout}\n{proc.stderr}")
    match = COLLECTED_RE.search(proc.stdout)
    if not match:
        raise RuntimeError(f"could not parse a collected count from:\n{proc.stdout[-2000:]}")
    return int(match.group(1))


def load_pin() -> dict[str, str]:
    return json.loads(PIN_PATH.read_text(encoding="utf-8"))


def markdown_pages(directory: Path, *, include_generated: bool = False) -> list[Path]:
    if not directory.is_dir():
        return []
    pages = []
    for path in sorted(directory.rglob("*.md")):
        if not include_generated and "_generated" in path.parts:
            continue
        pages.append(path)
    return pages


def static_facts() -> dict[str, object]:
    pin = load_pin()
    test_files = sorted((SOFTWARE / "tests").glob("test_*.py"))
    conftests = sorted((SOFTWARE / "tests").rglob("conftest.py"))
    modules = sorted(
        path
        for path in (SOFTWARE / "src").iterdir()
        if path.is_dir() and (path / "__init__.py").is_file()
    )
    scripts = sorted((SOFTWARE / "scripts").glob("*.py"))
    exemplars = sorted(path for path in MODELS_DIR.glob("*.md") if path.name != "README.md")
    return {
        "collected_tests": count_collected_tests(),
        "test_files": len(test_files),
        "no_mocks_files": len(test_files) + len(conftests),
        "src_modules": len(modules),
        "cli_scripts": len(scripts),
        "root_docs_pages": len(markdown_pages(ROOT / "docs")),
        "software_docs_pages": len(markdown_pages(SOFTWARE / "docs")),
        # The generated directory counts itself out: otherwise every change to
        # this file's own output would move the number it reports.
        "tracked_markdown": len(
            [
                path
                for path in subprocess.run(
                    ["git", "ls-files", "*.md"],
                    cwd=ROOT,
                    capture_output=True,
                    text=True,
                    check=True,
                ).stdout.splitlines()
                if not path.startswith("docs/_generated/")
            ]
        ),
        "gnn_schema": pin["schema"],
        "gnn_tag": pin["tag"],
        "gnn_revision": pin["revision"],
        "gnn_recorded": pin["recorded"],
        "gnn_exemplars": len(exemplars),
    }


def render_metrics(facts: dict[str, object]) -> str:
    return f"""# Gate metrics

<!-- generated by software/scripts/generate_gate_metrics.py; do not edit by hand -->

Structural facts about this repository, produced from the tree itself. Refresh
with `./run.sh metrics`; `./run.sh docs` fails if this file is stale.

| Fact | Value |
| --- | --- |
| Tests collected (`pytest --collect-only`) | {facts["collected_tests"]} |
| Test files (`software/tests/test_*.py`) | {facts["test_files"]} |
| Files scanned by the no-mocks check | {facts["no_mocks_files"]} |
| Importable modules (`software/src/*/__init__.py`) | {facts["src_modules"]} |
| Python scripts (`software/scripts/*.py`) | {facts["cli_scripts"]} |
| Pages under `docs/` (excluding `_generated/`) | {facts["root_docs_pages"]} |
| Pages under `software/docs/` | {facts["software_docs_pages"]} |
| Tracked Markdown files (excluding `docs/_generated/`) | {facts["tracked_markdown"]} |

## GNN pin

| Field | Value |
| --- | --- |
| Pin file | `.github/gnn-pin.json` |
| Schema | `{facts["gnn_schema"]}` |
| Tag | `{facts["gnn_tag"]}` |
| Revision | `{facts["gnn_revision"]}` |
| Recorded | {facts["gnn_recorded"]} |
| Exemplars checked | {facts["gnn_exemplars"]} |

The conformance check itself is `software/scripts/verify_gnn_conformance.py`,
run as `./run.sh gnn`. See [`.github/GNN.md`](../../.github/GNN.md) for what the
job parses and what it deliberately does not scan.
"""


def read_timings() -> dict[str, dict[str, object]]:
    """Return the newest receipt per arm."""
    latest: dict[str, dict[str, object]] = {}
    if not TIMINGS_LOG.is_file():
        return latest
    for line in TIMINGS_LOG.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            receipt = json.loads(line)
        except json.JSONDecodeError:
            continue
        arm = receipt.get("arm")
        if isinstance(arm, str):
            latest[arm] = receipt
    return latest


def read_coverage() -> str:
    if not COVERAGE_JSON.is_file():
        return "not measured (run `./run.sh test`)"
    try:
        data = json.loads(COVERAGE_JSON.read_text(encoding="utf-8"))
        percent = float(data["totals"]["percent_covered"])
    except (OSError, KeyError, TypeError, ValueError, json.JSONDecodeError):
        return "not measured (unreadable software/coverage.json)"
    return f"{percent:.0f}% of `software/src` (last `./run.sh test` run)"


def render_timings(timings: dict[str, dict[str, object]]) -> str:
    rows = []
    for arm in ARMS:
        receipt = timings.get(arm)
        if receipt is None:
            rows.append(f"| `{arm}` | not measured | - | - | - |")
            continue
        rows.append(
            "| `{arm}` | {seconds:.1f} s | {rc} | {host} | `{commit}` |".format(
                arm=arm,
                seconds=float(receipt.get("seconds", 0.0)),
                rc=receipt.get("rc", "?"),
                host=receipt.get("host", "?"),
                commit=str(receipt.get("commit", "?"))[:12],
            )
        )
    return f"""# Arm timings

<!-- generated by software/scripts/generate_gate_metrics.py; do not edit by hand -->

Wall time per gate arm, measured by `./run.sh` on the host named in each row.
One run per arm; these are observations, not guarantees. `./run.sh metrics`
rewrites this table from `arm-timings.jsonl` (the receipts `./run.sh` appends
when `CI` is unset).

| Arm | Wall time | Exit | Host | Commit |
| --- | --- | --- | --- | --- |
{chr(10).join(rows)}

Coverage: {read_coverage()}.

The commands behind each arm are listed in [`../RUN_GUIDE.md`](../RUN_GUIDE.md).
"""


def write_or_check(path: Path, content: str, *, check: bool) -> bool:
    if check:
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current != content:
            print(f"stale generated document: {_rel(path)} (run ./run.sh metrics)", file=sys.stderr)
            return False
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {_rel(path)}")
    return True


def check_timings_shape(path: Path) -> bool:
    if not path.is_file():
        print(f"missing generated document: {_rel(path)} (run ./run.sh metrics)", file=sys.stderr)
        return False
    text = path.read_text(encoding="utf-8")
    missing = [arm for arm in ARMS if f"`{arm}`" not in text]
    if missing:
        print(f"{_rel(path)} has no row for: {', '.join(missing)}", file=sys.stderr)
        return False
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify the documents are current")
    args = parser.parse_args(argv)

    try:
        facts = static_facts()
    except (OSError, RuntimeError, KeyError, subprocess.CalledProcessError) as exc:
        print(f"cannot compute gate metrics: {exc}", file=sys.stderr)
        return 1

    ok = write_or_check(METRICS_PATH, render_metrics(facts), check=args.check)
    timings_doc = render_timings(read_timings())
    if args.check:
        ok = check_timings_shape(TIMINGS_PATH) and ok
    else:
        ok = write_or_check(TIMINGS_PATH, timings_doc, check=False) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
